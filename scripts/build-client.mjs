import { readFileSync, writeFileSync } from 'node:fs'
import vm from 'node:vm'
import { createRequire } from 'node:module'
import { createUiTheme } from '../lib/ui-theme.js'
import { createTaskIndicatorStore } from '../lib/task-indicator-store.js'

const require = createRequire(import.meta.url)
const packageName = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).name
if (!packageName) throw new Error('package.json name is required for the Client module id')

// Capture declarations only; never execute either Client factory during build.
function factoryOf(file) {
  let factory
  vm.runInNewContext(readFileSync(new URL(`../${file}`, import.meta.url), 'utf8'), {
    window: { __ModuleLoader__: { load(entry) {
      if (factory || typeof entry.factory !== 'function') throw new Error(`Invalid module declaration in ${file}`)
      factory = entry.factory.toString()
    } } },
  }, { timeout: 1000 })
  if (!factory) throw new Error(`No Client factory in ${file}`)
  // Object method syntax is not a standalone function expression.
  return factory.startsWith('factory(') ? `function ${factory}` : factory
}
const settings = factoryOf('client.js')
const tasks = factoryOf('tasks-client.js')
const direct = factoryOf('direct-client.js')
const agentIcons = Object.fromEntries(['deepseek', 'openai', 'kimi', 'google'].map((id) => [
  id, readFileSync(new URL(`../assets/icons/${id}.svg`, import.meta.url), 'utf8'),
]))
const uiThemeFactory = createUiTheme.toString()
const taskIndicatorStoreFactory = createTaskIndicatorStore.toString()
// Embed the dependency's self-contained browser build in a private CommonJS
// scope. This adds no browser runtime imports, global writes, eval, or CDN load.
const markdown = readFileSync(require.resolve('markdown-it/dist/markdown-it.min.js'), 'utf8')
const output = `// Generated by scripts/build-client.mjs; edit client.js, tasks-client.js, direct-client.js, assets/icons/*.svg, lib/ui-theme.js, or lib/task-indicator-store.js.\n// Third-party licenses: THIRD_PARTY_NOTICES.md.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(packageName)},\n  factory(require) {\n    const markdownIt = (() => {\n      const module = { exports: {} };\n      const exports = module.exports;\n${markdown}\n      return module.exports;\n    })();\n    const uiTheme = (${uiThemeFactory})(typeof window !== 'undefined' ? window : undefined);\n    const taskIndicatorStore = (${taskIndicatorStoreFactory});\n    const agentIcons = ${JSON.stringify(agentIcons)};
    const bundleRequire = (id) => id === 'dsh-multi-agent/ui-theme' ? uiTheme : id === 'dsh-multi-agent/task-indicator-store' ? taskIndicatorStore : id === 'dsh-multi-agent/agent-icons' ? agentIcons : id === 'markdown-it' ? markdownIt : require(id);\n    const shared = {};\n    const settings = (${settings})(bundleRequire, shared);\n    const tasks = (${tasks})(bundleRequire, shared);\n    const direct = (${direct})(bundleRequire, shared);\n    return {\n      inject: settings.inject,\n      apply(ctx) {\n        settings.apply(ctx);\n        ctx.inject(direct.inject, (child) => direct.apply(child));\n        ctx.inject(tasks.inject, (child) => tasks.apply(child));\n      },\n    };\n  },\n});\n`
writeFileSync(new URL('../client-bundle.js', import.meta.url), output)

import { readFileSync, writeFileSync } from 'node:fs'
import vm from 'node:vm'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const packageName = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).name
if (!packageName) throw new Error('package.json name is required for the Client module id')

// Capture declarations only; never execute either Client factory during build.
function factoryOf(file) {
  let factory
  vm.runInNewContext(readFileSync(new URL(`../${file}`, import.meta.url), 'utf8'), {
    window: { __ModuleLoader__: { load(entry) {
      if (factory || typeof entry.factory !== 'function') throw new Error(`Invalid module declaration in ${file}`)
      factory = entry.factory.toString()
    } } },
  }, { timeout: 1000 })
  if (!factory) throw new Error(`No Client factory in ${file}`)
  // Object method syntax is not a standalone function expression.
  return factory.startsWith('factory(') ? `function ${factory}` : factory
}
const settings = factoryOf('client.js')
const tasks = factoryOf('tasks-client.js')
// Embed the dependency's self-contained browser build in a private CommonJS
// scope. This adds no browser runtime imports, global writes, eval, or CDN load.
const markdown = readFileSync(require.resolve('markdown-it/dist/markdown-it.min.js'), 'utf8')
const output = `// Generated by scripts/build-client.mjs; edit client.js or tasks-client.js.\n// Third-party licenses: THIRD_PARTY_NOTICES.md.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(packageName)},\n  factory(require) {\n    const markdownIt = (() => {\n      const module = { exports: {} };\n      const exports = module.exports;\n${markdown}\n      return module.exports;\n    })();\n    const taskRequire = (id) => id === 'markdown-it' ? markdownIt : require(id);\n    const settings = (${settings})(require);\n    const tasks = (${tasks})(taskRequire);\n    return {\n      inject: settings.inject,\n      apply(ctx) {\n        settings.apply(ctx);\n        ctx.inject(tasks.inject, (child) => tasks.apply(child));\n      },\n    };\n  },\n});\n`
writeFileSync(new URL('../client-bundle.js', import.meta.url), output)
